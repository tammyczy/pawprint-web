import {readFileSync,copyFileSync,writeFileSync,existsSync} from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {openStore,updateJob} from './store.mjs';
const root=path.resolve(import.meta.dirname,'..');
const id='64989a83-4ed5-4708-9062-b67aa2892ecd';
const source=path.resolve(root,'../white-cat-model/white-cat-eye-v2.glb');
const parse=file=>{const b=readFileSync(file);assert.equal(b.toString('ascii',0,4),'glTF');return JSON.parse(b.toString('utf8',20,20+b.readUInt32LE(12)).trim());};
const original=parse(path.resolve(root,'../white-cat-model/white-cat-walk.glb'));
const revised=parse(source);
assert.equal(revised.meshes.length,1);
assert.equal(revised.skins[0].joints.length,original.skins[0].joints.length);
assert.ok(revised.animations?.some(a=>a.name.includes('quadruped:walk')));
assert.ok(revised.materials[0].pbrMetallicRoughness.baseColorTexture);
const db=openStore(path.join(root,'.data'));
const job=db.prepare('SELECT * FROM jobs WHERE id=?').get(id);
const data=JSON.parse(job.data);
const backup=path.join(root,'.data/assets',id,'before-eye-v2-job.json');
if(!existsSync(backup))writeFileSync(backup,JSON.stringify(job,null,2));
copyFileSync(source,path.join(root,'.data/assets',id,'model-eye-v2.glb'));
data.modelFile='model-eye-v2.glb';
data.eyeRefinement={version:2,tool:'Blender',originalModel:'model.glb',changes:['Local inner-eye texture correction','Small upper-eyelid proportional adjustment'],at:new Date().toISOString()};
updateJob(db,id,{data,message:'Blender 眼周微调版：淡化眼角黑斑，保留原毛色、绿眼睛和走路动画。'});
db.close();
console.log(JSON.stringify({meshes:revised.meshes.length,joints:revised.skins[0].joints.length,animations:revised.animations.map(a=>a.name),images:revised.images.length,published:data.modelFile}));
